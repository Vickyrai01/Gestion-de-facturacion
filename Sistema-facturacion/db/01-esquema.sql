-- Esquema FACTURACION_APP tal como lo mapea FacturacionDbContext.
-- Se ejecuta como SYS la primera vez que arranca el contenedor.

ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE USER facturacion_app IDENTIFIED BY "TuPasswordSeguro123"
  DEFAULT TABLESPACE users
  QUOTA UNLIMITED ON users;

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO facturacion_app;

CREATE TABLE facturacion_app.usuarios (
  id            NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombreusuario VARCHAR2(50)  NOT NULL,
  passwordhash  VARCHAR2(100) NOT NULL,
  rol           VARCHAR2(10)  NOT NULL,
  activo        NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT ux_usuario_nombre UNIQUE (nombreusuario)
);

CREATE TABLE facturacion_app.clientes (
  id        NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombre    VARCHAR2(100) NOT NULL,
  apellido  VARCHAR2(100) NOT NULL,
  documento VARCHAR2(30)  NOT NULL,
  email     VARCHAR2(254) NOT NULL,
  activo    NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE facturacion_app.productos (
  id             NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  codigo         VARCHAR2(30)  NOT NULL,
  nombre         VARCHAR2(100) NOT NULL,
  descripcion    VARCHAR2(500),
  preciounitario NUMBER(18,2)  NOT NULL,
  stock          NUMBER(10)    NOT NULL,
  activo         NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT ux_producto_codigo UNIQUE (codigo)
);

CREATE TABLE facturacion_app.facturas (
  id           NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  numero       VARCHAR2(30) NOT NULL,
  clienteid    NUMBER(10)   NOT NULL,
  fechaemision TIMESTAMP(6) NOT NULL,
  estado       VARCHAR2(10) NOT NULL,
  subtotal     NUMBER(18,2) NOT NULL,
  impuestos    NUMBER(18,2) NOT NULL,
  total        NUMBER(18,2) NOT NULL,
  CONSTRAINT ux_factura_numero UNIQUE (numero),
  CONSTRAINT fk_facturas_clientes FOREIGN KEY (clienteid) REFERENCES facturacion_app.clientes (id)
);

CREATE TABLE facturacion_app.detallesfactura (
  id             NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  facturaid      NUMBER(10)   NOT NULL,
  productoid     NUMBER(10)   NOT NULL,
  cantidad       NUMBER(10)   NOT NULL,
  preciounitario NUMBER(18,2) NOT NULL,
  subtotal       NUMBER(18,2) NOT NULL,
  CONSTRAINT fk_detalles_facturas  FOREIGN KEY (facturaid)  REFERENCES facturacion_app.facturas (id),
  CONSTRAINT fk_detalles_productos FOREIGN KEY (productoid) REFERENCES facturacion_app.productos (id)
);
